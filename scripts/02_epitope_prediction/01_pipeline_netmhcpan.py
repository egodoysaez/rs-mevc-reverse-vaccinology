#!/usr/bin/env python3
"""
MHC-I prediction with NetMHCpan 4.1b in BA (binding affinity) mode.

Original author: Esteban Godoy Sáez, RS-MEVC pipeline, 2025.

For each Sasa-UBA allele:
  1. Clean the sequence (remove gaps `-`, stop codons `*`, and spaces).
  2. Run NetMHCpan 4.1b with -BA and peptide length 9 against the
     Top-15 consensus proteins.
  3. Save the detailed table to <output-dir>/allele_XX.txt.

Alleles that cannot be processed (gap in the pseudo-sequence) produce
an error file <output-dir>/allele_XX.txt.err and are skipped downstream.

Note
----
NetMHCpan was trained on mammalian MHC. For 13/48 Sasa-UBA alleles the
pseudo-sequence generated by NetMHCpan contains gaps and the prediction
fails. This is an expected limitation of the method (see
docs/02_epitope_prediction.md).
"""

import argparse
import os
import subprocess
import sys
from pathlib import Path


def clean_sequence(seq: str) -> str:
    """Remove gaps, stop codons and spaces; uppercase."""
    return seq.replace("-", "").replace("*", "").replace(" ", "").upper()


def split_alleles(alleles_file: str, temp_dir: str) -> int:
    """
    Split a multi-FASTA file of MHC alleles into individual cleaned files.

    Returns the number of alleles written.
    """
    os.makedirs(temp_dir, exist_ok=True)
    count = 0
    header, seq = None, ""

    def _flush(h: str, s: str, idx: int):
        out = os.path.join(temp_dir, f"allele_{idx:02d}.fsa")
        with open(out, "w") as fh:
            fh.write(f"{h}\n{clean_sequence(s)}\n")

    with open(alleles_file, "r") as fh:
        for line in fh:
            line = line.rstrip("\n")
            if line.startswith(">"):
                if header is not None:
                    count += 1
                    _flush(header, seq, count)
                header, seq = line, ""
            else:
                seq += line
        if header is not None:
            count += 1
            _flush(header, seq, count)

    return count


def run_netmhcpan(
    netmhcpan_bin: str,
    nmhome: str,
    proteins: str,
    temp_dir: str,
    output_dir: str,
    peptide_length: int,
    timeout: int,
) -> tuple[int, int]:
    """Run NetMHCpan once per allele. Returns (n_success, n_error)."""
    os.makedirs(output_dir, exist_ok=True)

    env = os.environ.copy()
    env["NMHOME"] = nmhome
    env["NETMHCpan"] = nmhome
    env.setdefault("TMPDIR", os.path.join(nmhome, "tmp"))

    allele_files = sorted(Path(temp_dir).glob("allele_*.fsa"))
    n_success = n_error = 0

    for i, allele_file in enumerate(allele_files, 1):
        allele_name = allele_file.stem
        output_file = os.path.join(output_dir, f"{allele_name}.txt")

        cmd = [
            netmhcpan_bin,
            "-rdir", nmhome,
            "-hlaseq", str(allele_file),
            "-BA",
            "-l", str(peptide_length),
            proteins,
        ]

        print(f"[{i}/{len(allele_files)}] {allele_name} ... ", end="", flush=True)
        try:
            with open(output_file, "w") as out:
                result = subprocess.run(
                    cmd, stdout=out, stderr=subprocess.PIPE,
                    env=env, timeout=timeout,
                )
            if result.returncode == 0:
                print("OK")
                n_success += 1
            else:
                print("ERROR (see .err file)")
                with open(output_file + ".err", "w") as err:
                    err.write(result.stderr.decode(errors="replace"))
                n_error += 1
        except subprocess.TimeoutExpired:
            print("TIMEOUT")
            n_error += 1
        except Exception as exc:  # noqa: BLE001
            print(f"EXCEPTION: {exc}")
            n_error += 1

    return n_success, n_error


def main():
    parser = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("--netmhcpan-bin", required=True,
                        help="Full path to the netMHCpan binary.")
    parser.add_argument("--nmhome", required=True,
                        help="NetMHCpan installation directory (for -rdir).")
    parser.add_argument("--proteins", required=True,
                        help="FASTA with the Top-15 consensus proteins.")
    parser.add_argument("--alleles", required=True,
                        help="Multi-FASTA with the Sasa-UBA alleles.")
    parser.add_argument("--output-dir", required=True,
                        help="Directory for the per-allele NetMHCpan tables.")
    parser.add_argument("--temp-dir", required=True,
                        help="Directory for the split allele FASTA files.")
    parser.add_argument("--peptide-length", type=int, default=9,
                        help="Peptide length (default: 9).")
    parser.add_argument("--timeout", type=int, default=120,
                        help="Per-allele timeout in seconds (default: 120).")
    args = parser.parse_args()

    if not os.path.isfile(args.netmhcpan_bin):
        sys.exit(f"ERROR: NetMHCpan binary not found: {args.netmhcpan_bin}")
    for label, path in (("proteins", args.proteins), ("alleles", args.alleles)):
        if not os.path.isfile(path):
            sys.exit(f"ERROR: {label} file not found: {path}")

    print("=" * 70)
    print("MHC-I prediction with NetMHCpan 4.1b (BA mode)")
    print("=" * 70)

    print("\nStep 1: Splitting alleles ...")
    n_alleles = split_alleles(args.alleles, args.temp_dir)
    print(f"  → {n_alleles} allele files written to {args.temp_dir}")

    print("\nStep 2: Running NetMHCpan per allele ...")
    n_ok, n_err = run_netmhcpan(
        netmhcpan_bin=args.netmhcpan_bin,
        nmhome=args.nmhome,
        proteins=args.proteins,
        temp_dir=args.temp_dir,
        output_dir=args.output_dir,
        peptide_length=args.peptide_length,
        timeout=args.timeout,
    )

    print("\n" + "=" * 70)
    print(f"Done: {n_ok} alleles succeeded, {n_err} failed.")
    print(f"Outputs in: {args.output_dir}")
    if n_err:
        print("\nNote: alleles that failed usually contain gaps in the")
        print("pseudo-sequence and are a documented NetMHCpan limitation")
        print("for salmonid MHC. See docs/02_epitope_prediction.md.")
    print("=" * 70)


if __name__ == "__main__":
    main()